import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createSubwayServer } from '../server.mjs';
import { TransitProvider } from '../transit.mjs';

test('cabin presence and bounded walking stay within the train and respect blocking and leaving', async t => {
  let time = Date.now();
  const { server } = createSubwayServer({ secure: false, now: () => time, provider: new TransitProvider({ demo: true, now: () => time }) });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`, api = base + '/metro-chat/api/';
  const abort = new AbortController();
  t.after(() => { abort.abort(); server.closeAllConnections(); server.close(); });
  const post = (name, data, cookie) => fetch(api + name, { method: 'POST', headers: { Origin: base, 'Content-Type': 'application/json', Cookie: cookie || '' }, body: JSON.stringify(data) });
  const join = async () => { const response = await post('session', {}); return { cookie: response.headers.get('set-cookie').split(';')[0], state: await response.json() }; };
  const a = await join(), b = await join(), c = await join();
  assert.equal((await post('move', { x: 0, z: 0 }, a.cookie)).status, 409);
  const trip = { line: '1002', from: '강남', to: '사당', direction: 0, train: 'demo-0' };
  for (const passenger of [a, b]) await post('board', trip, passenger.cookie);
  await post('board', { ...trip, direction: 1, train: 'demo-1' }, c.cookie);
  for (const passenger of [a, b, c]) await fetch(api + 'events', { headers: { Cookie: passenger.cookie }, signal: abort.signal });
  const snapshot = async passenger => (await post('session', {}, passenger.cookie)).json();
  let state = await snapshot(b);
  assert.equal(state.count, 2); assert.deepEqual(new Set(state.players.map(p => p.id)), new Set([a.state.id, b.state.id]));
  const start = state.players.find(p => p.id === a.state.id);
  assert.equal((await post('move', { x: null, z: 0 }, a.cookie)).status, 400);
  assert.equal((await post('move', { x: 1000, z: -1000 }, a.cookie)).status, 200);
  assert.equal((await post('move', { x: 0, z: 0 }, a.cookie)).status, 429);
  time += 1000;
  const moving = (await snapshot(b)).players.find(p => p.id === a.state.id);
  assert.ok(Math.hypot(moving.x - start.x, moving.z - start.z) <= 2.2 + 1e-6);
  time += 20000;
  const end = (await snapshot(b)).players.find(p => p.id === a.state.id);
  assert.equal(end.x, 1.15); assert.equal(end.z, -9);
  await post('say', { text: '객실 말풍선' }, a.cookie);
  const message = (await snapshot(b)).messages[0];
  state = await (await post('block', { messageId: message.id }, b.cookie)).json();
  assert.ok(!state.players.some(p => p.id === a.state.id)); assert.equal(state.messages.length, 0);
  time += 1200;
  state = await (await post('unblock', { sender: a.state.id }, b.cookie)).json();
  assert.ok(state.players.some(p => p.id === a.state.id));
  await post('leave', {}, a.cookie);
  assert.equal((await post('move', { x: 0, z: 0 }, a.cookie)).status, 409);
  state = await snapshot(b); assert.equal(state.count, 1); assert.deepEqual(state.players.map(p => p.id), [b.state.id]);
  for (const file of ['cabin.js', 'vendor/three.module.min.js']) assert.equal((await fetch(base + '/metro-chat/' + file)).status, 200);
  assert.match((await fetch(base + '/metro-chat/cabin.css')).headers.get('content-type'), /text\/css/);
  assert.equal((await fetch(base + '/metro-chat/vendor/../server.mjs')).status, 404);
});

test('cars share train chat but isolate car chat, seats and reactions; transitions preserve the trip', async t => {
  let time = Date.now();
  const { server, sessions } = createSubwayServer({ secure: false, now: () => time, provider: new TransitProvider({ demo: true, now: () => time }) });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`, path = base + '/metro-chat/api/';
  const abort = new AbortController();
  t.after(() => { abort.abort(); server.closeAllConnections(); server.close(); });
  const post = async (name, data, cookie) => { time += 1000; return fetch(path + name, { method: 'POST', headers: { Origin: base, 'Content-Type': 'application/json', Cookie: cookie || '' }, body: JSON.stringify(data) }); };
  const a = await post('session', {}), b = await post('session', {});
  const ac = a.headers.get('set-cookie').split(';')[0], bc = b.headers.get('set-cookie').split(';')[0];
  const aid = (await a.json()).id;
  const trip = { line: '1002', from: '강남', to: '사당', direction: 0, train: 'demo-0' };
  const original = await (await post('board', trip, ac)).json(); await post('board', trip, bc);
  for (const cookie of [ac, bc]) await fetch(path + 'events', { headers: { Cookie: cookie }, signal: abort.signal });
  const state = async cookie => (await post('session', {}, cookie)).json();
  assert.equal((await post('car', { car: 0 }, ac)).status, 400);
  assert.equal((await post('car', { car: 7 }, ac)).status, 400);
  assert.equal((await post('car', { car: 1.5 }, ac)).status, 400);
  let moved = await (await post('car', { car: 2 }, ac)).json();
  assert.equal(moved.trip.room, original.trip.room); assert.equal(moved.trip.boardedAt, original.trip.boardedAt); assert.equal(moved.trip.to, '사당');
  assert.deepEqual(moved.cars.map(c => c.count), [1, 1, 0, 0, 0, 0]);
  assert.equal((await state(bc)).players.find(p => p.id === aid).car, 2);
  await post('say', { text: '2칸 안에서만', scope: 'car' }, ac);
  assert.ok(!(await state(bc)).messages.some(m => m.text === '2칸 안에서만'));
  await post('say', { text: '열차 전체에', scope: 'train' }, ac);
  assert.ok((await state(bc)).messages.some(m => m.text === '열차 전체에'));
  await post('car', { car: 2 }, bc);
  assert.ok((await state(bc)).messages.some(m => m.text === '2칸 안에서만'));
  assert.equal((await post('seat', { seat: 'forged' }, ac)).status, 400);
  assert.equal((await post('seat', { seat: '-1:0:0' }, ac)).status, 200);
  assert.equal((await post('seat', { seat: '-1:0:0' }, bc)).status, 409);
  await post('car', { car: 3 }, bc);
  assert.equal((await post('seat', { seat: '-1:0:0' }, bc)).status, 200);
  await post('car', { car: 2 }, bc);
  assert.equal((await state(bc)).players.find(p => p.id !== aid).seat, null);
  await post('move', { x: 0, z: 0 }, ac);
  assert.equal((await state(ac)).players.find(p => p.id === aid).seat, null);
  assert.equal((await post('seat', { seat: '-1:0:0' }, bc)).status, 200);
  let reaction = await (await post('emote', { kind: 'wave' }, ac)).json();
  assert.equal(reaction.players.find(p => p.id === aid).emote.kind, 'wave');
  assert.equal((await post('emote', { kind: '__proto__' }, ac)).status, 400);
  time += 5000; assert.equal((await state(bc)).players.find(p => p.id === aid).emote, null);
  assert.equal((await post('appearance', { coat: 4 }, ac)).status, 200);
  assert.equal((await state(bc)).players.find(p => p.id === aid).coat, 4);
  assert.equal((await post('appearance', { coat: 9 }, ac)).status, 400);
  const actual = [...sessions.values()].find(s => s.id === aid); actual.trip = null;
  for (const [name, data] of [['car', { car: 2 }], ['seat', { seat: null }], ['emote', { kind: 'wave' }]]) assert.equal((await post(name, data, ac)).status, 409);
});
